'''Assigning Slices
Replacing a part of list (a slice) with new values'''

fruits=["apple","orange","cherry","mango"]
print(fruits)
fruits[1:3]=["kiwi","banana"]
print(fruits)

nums=[10,20,30,40,50,60,70]
print(nums)
nums[1:5]=[80,90]
print(nums)

nums=[1,2,3,4,5]
print(nums)
nums[1:2]=[6,7,8,9,10]
print(nums)